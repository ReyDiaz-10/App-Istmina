CREATE OR REPLACE FUNCTION public.complete_pickup_order_with_code(p_order_id UUID, p_code TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp AS $$
DECLARE
  v_order public.orders%ROWTYPE;
  v_expected_hash TEXT;
  v_failed_attempts SMALLINT;
  v_window_started_at TIMESTAMPTZ;
  v_locked_until TIMESTAMPTZ;
  v_now TIMESTAMPTZ;
BEGIN
  SELECT o.* INTO v_order
  FROM public.orders o
  JOIN public.businesses b ON b.id = o.business_id AND b.profile_id = auth.uid()
  WHERE o.id = p_order_id AND o.delivery_mode = 'pickup'
  FOR UPDATE OF o;
  IF NOT FOUND OR NOT EXISTS (
    SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role::TEXT = 'negocio'
  ) THEN RAISE EXCEPTION 'Pickup order not found for this business' USING ERRCODE = '42501'; END IF;
  IF v_order.status::TEXT = 'entregado' THEN RETURN TRUE; END IF;
  IF v_order.status::TEXT <> 'preparando' THEN
    RAISE EXCEPTION 'Pickup order is not ready to be claimed';
  END IF;
  SELECT pickup_code_hash INTO v_expected_hash FROM public.order_verification_secrets
    WHERE order_id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pickup verification code is unavailable'; END IF;
  v_now := clock_timestamp();
  INSERT INTO public.pickup_order_code_verification_attempts (order_id, failed_attempts, window_started_at)
  VALUES (p_order_id, 0, v_now)
  ON CONFLICT (order_id) DO NOTHING;
  SELECT failed_attempts, window_started_at, locked_until
    INTO v_failed_attempts, v_window_started_at, v_locked_until
  FROM public.pickup_order_code_verification_attempts WHERE order_id = p_order_id FOR UPDATE;
  IF v_locked_until IS NOT NULL AND v_locked_until > v_now THEN RETURN FALSE; END IF;
  IF v_window_started_at <= v_now - INTERVAL '15 minutes' THEN
    v_failed_attempts := 0;
    UPDATE public.pickup_order_code_verification_attempts
    SET failed_attempts = 0, window_started_at = v_now, locked_until = NULL
    WHERE order_id = p_order_id;
  END IF;
  IF NOT COALESCE(p_code ~ '^[0-9]{6}$', FALSE)
     OR v_expected_hash <> encode(extensions.digest(p_code, 'sha256'), 'hex') THEN
    UPDATE public.pickup_order_code_verification_attempts
    SET failed_attempts = failed_attempts + 1,
        locked_until = CASE WHEN failed_attempts + 1 >= 5
          THEN v_now + INTERVAL '15 minutes' ELSE NULL END
    WHERE order_id = p_order_id;
    RETURN FALSE;
  END IF;
  UPDATE public.orders SET status = 'entregado' WHERE id = p_order_id AND status::TEXT = 'preparando';
  IF NOT FOUND THEN RAISE EXCEPTION 'Pickup order status changed during verification'; END IF;
  DELETE FROM public.pickup_order_code_verification_attempts WHERE order_id = p_order_id;
  INSERT INTO public.business_settlement_items (order_id, business_id, amount_cop, status)
  VALUES (v_order.id, v_order.business_id, COALESCE(v_order.product_subtotal_cop, v_order.total_amount), 'available')
  ON CONFLICT (order_id) DO NOTHING;
  PERFORM public.write_system_audit_log(auth.uid(), 'confirmó retiro de pedido en tienda',
    'order', p_order_id::TEXT, jsonb_build_object(
      'business_id', v_order.business_id, 'total_amount', v_order.total_amount,
      'settlement_amount_cop', COALESCE(v_order.product_subtotal_cop, v_order.total_amount)));
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.complete_pickup_order_with_code(UUID, TEXT) FROM PUBLIC, anon;

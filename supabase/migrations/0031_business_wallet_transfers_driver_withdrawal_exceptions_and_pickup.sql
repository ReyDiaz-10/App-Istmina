CREATE OR REPLACE FUNCTION public.delivery_demand_status(p_business_id UUID)
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_open_orders INTEGER;
  v_couriers INTEGER;
  v_min_orders INTEGER;
  v_ratio NUMERIC;
  v_orders_paused BOOLEAN;
  v_high_demand BOOLEAN;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.businesses WHERE id = p_business_id AND (profile_id = auth.uid() OR public.is_admin())
  ) THEN RAISE EXCEPTION 'Business access denied' USING ERRCODE = '42501'; END IF;
  SELECT minimum_open_delivery_orders, minimum_courier_ratio INTO v_min_orders, v_ratio
    FROM public.delivery_demand_settings WHERE id;
  SELECT orders_paused INTO v_orders_paused FROM public.businesses WHERE id = p_business_id;
  SELECT COUNT(*) INTO v_open_orders FROM public.orders WHERE delivery_mode = 'delivery'
    AND status::TEXT IN (
      'pagado','preparando','listo_para_repartidor','repartidor_asignado',
      'recogido','en_camino','no_entregado'
    );
  SELECT COUNT(DISTINCT d.id) INTO v_couriers FROM public.drivers d
  WHERE d.is_available AND d.verification_status = 'aprobado'
    AND NOT EXISTS (
      SELECT 1 FROM public.orders o
      WHERE o.driver_id = d.id AND o.delivery_mode = 'delivery'
        AND o.status::TEXT IN (
          'preparando','repartidor_asignado','recogido','en_camino','no_entregado'
        )
    );
  v_high_demand := v_open_orders >= COALESCE(v_min_orders, 5)
    AND (v_couriers = 0 OR v_open_orders::NUMERIC / v_couriers >= COALESCE(v_ratio, 1.5));
  RETURN jsonb_build_object('open_delivery_orders', v_open_orders, 'available_drivers', v_couriers,
    'high_demand', v_high_demand, 'suggest_pause', v_high_demand,
    'orders_paused', COALESCE(v_orders_paused, FALSE),
    'minimum_open_delivery_orders', COALESCE(v_min_orders, 5),
    'minimum_courier_ratio', COALESCE(v_ratio, 1.5));
END;
$$;

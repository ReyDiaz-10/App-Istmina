-- Business prepaid wallet transfers are proposals until explicitly accepted.
CREATE TABLE IF NOT EXISTS public.business_wallet_transfers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  sender_business_id UUID NOT NULL REFERENCES public.businesses(id) ON DELETE RESTRICT,
  recipient_business_id UUID NOT NULL REFERENCES public.businesses(id) ON DELETE RESTRICT,
  amount_cop NUMERIC(12,2) NOT NULL CHECK (amount_cop > 0),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined', 'cancelled')),
  idempotency_key UUID NOT NULL,
  decision_reason TEXT,
  created_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  decided_by UUID REFERENCES public.profiles(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  decided_at TIMESTAMPTZ,
  UNIQUE (sender_business_id, idempotency_key),
  CHECK (sender_business_id <> recipient_business_id)
);
CREATE INDEX IF NOT EXISTS business_wallet_transfers_recipient_status_idx
  ON public.business_wallet_transfers (recipient_business_id, status, created_at DESC);
ALTER TABLE public.business_wallet_transfers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.business_wallet_transfers FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.business_wallet_transfers TO authenticated;
CREATE POLICY business_wallet_transfers_participant_read
  ON public.business_wallet_transfers FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.businesses b
    WHERE b.profile_id = auth.uid()
      AND b.id IN (sender_business_id, recipient_business_id)
  ) OR public.is_admin());

CREATE TABLE IF NOT EXISTS public.business_wallet_transfer_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_id UUID NOT NULL REFERENCES public.business_wallet_transfers(id) ON DELETE RESTRICT,
  business_id UUID NOT NULL REFERENCES public.businesses(id) ON DELETE RESTRICT,
  entry_type TEXT NOT NULL CHECK (entry_type IN ('transfer_debit', 'transfer_credit')),
  amount_cop NUMERIC(12,2) NOT NULL CHECK (amount_cop > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (transfer_id, entry_type)
);
ALTER TABLE public.business_wallet_transfer_entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.business_wallet_transfer_entries FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.business_wallet_transfer_entries TO authenticated;
CREATE POLICY business_wallet_transfer_entries_participant_read
  ON public.business_wallet_transfer_entries FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.businesses b
    WHERE b.profile_id = auth.uid() AND b.id = business_id
  ) OR public.is_admin());

CREATE TABLE IF NOT EXISTS public.business_wallet_transfer_reconciliation_cases (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  transfer_id UUID REFERENCES public.business_wallet_transfers(id) ON DELETE RESTRICT,
  business_id UUID NOT NULL REFERENCES public.businesses(id) ON DELETE RESTRICT,
  reason TEXT NOT NULL CHECK (reason IN ('duplicate_wallets', 'missing_wallet')),
  observed_wallet_count INTEGER NOT NULL CHECK (observed_wallet_count >= 0),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
  admin_note TEXT,
  created_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  reviewed_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS business_wallet_transfer_case_transfer_business_uidx
  ON public.business_wallet_transfer_reconciliation_cases (transfer_id, business_id)
  WHERE transfer_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS business_wallet_transfer_case_legacy_open_uidx
  ON public.business_wallet_transfer_reconciliation_cases (business_id, reason)
  WHERE transfer_id IS NULL AND status = 'open';
ALTER TABLE public.business_wallet_transfer_reconciliation_cases ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.business_wallet_transfer_reconciliation_cases FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.business_wallet_transfer_reconciliation_cases TO authenticated;
CREATE POLICY business_wallet_transfer_cases_participant_read
  ON public.business_wallet_transfer_reconciliation_cases FOR SELECT TO authenticated
  USING (public.is_admin() OR EXISTS (
    SELECT 1 FROM public.businesses b WHERE b.id = business_id AND b.profile_id = auth.uid()
  ));

INSERT INTO public.business_wallet_transfer_reconciliation_cases (
  business_id, reason, observed_wallet_count
)
SELECT business_id, 'duplicate_wallets', COUNT(*)::INTEGER
FROM public.wallets
WHERE business_id IS NOT NULL
GROUP BY business_id
HAVING COUNT(*) > 1
ON CONFLICT (business_id, reason)
  WHERE transfer_id IS NULL AND status = 'open'
DO UPDATE SET observed_wallet_count = EXCLUDED.observed_wallet_count, updated_at = NOW();

CREATE OR REPLACE FUNCTION public.enforce_single_business_wallet()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_existing_wallet_id UUID;
BEGIN
  IF NEW.business_id IS NULL THEN
    RAISE EXCEPTION 'A business wallet must belong to a business';
  END IF;
  PERFORM 1 FROM public.businesses WHERE id = NEW.business_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Business wallet owner not found'; END IF;
  SELECT id INTO v_existing_wallet_id FROM public.wallets
  WHERE business_id = NEW.business_id AND id IS DISTINCT FROM NEW.id
  LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'Business has multiple wallet records; administrative reconciliation is required';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.enforce_single_business_wallet() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS enforce_single_business_wallet ON public.wallets;
CREATE TRIGGER enforce_single_business_wallet
  BEFORE INSERT OR UPDATE OF business_id ON public.wallets
  FOR EACH ROW EXECUTE FUNCTION public.enforce_single_business_wallet();

CREATE OR REPLACE FUNCTION public.propose_business_wallet_transfer(
  p_recipient_business_id UUID,
  p_amount_cop NUMERIC,
  p_idempotency_key UUID
)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_sender_id UUID;
  v_sender_wallet UUID;
  v_wallet_count INTEGER;
  v_balance NUMERIC(12,2);
  v_created BOOLEAN;
  v_transfer public.business_wallet_transfers%ROWTYPE;
BEGIN
  SELECT id INTO v_sender_id FROM public.businesses
  WHERE profile_id = auth.uid() ORDER BY id LIMIT 1 FOR SHARE;
  IF v_sender_id IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role::TEXT = 'negocio')
     OR p_recipient_business_id IS NULL OR p_idempotency_key IS NULL
     OR p_amount_cop IS NULL OR p_amount_cop <= 0 OR p_amount_cop <> ROUND(p_amount_cop, 2) THEN
    RAISE EXCEPTION 'Invalid business wallet transfer request' USING ERRCODE = '22023';
  END IF;
  IF v_sender_id = p_recipient_business_id OR NOT EXISTS (
    SELECT 1 FROM public.businesses b JOIN public.profiles p ON p.id = b.profile_id
    WHERE b.id = p_recipient_business_id AND b.status = 'activo' AND p.role::TEXT = 'negocio'
  ) THEN
    RAISE EXCEPTION 'Recipient business is unavailable';
  END IF;

  INSERT INTO public.business_wallet_transfers (
    sender_business_id, recipient_business_id, amount_cop, idempotency_key, created_by
  ) VALUES (v_sender_id, p_recipient_business_id, p_amount_cop, p_idempotency_key, auth.uid())
  ON CONFLICT (sender_business_id, idempotency_key) DO NOTHING
  RETURNING TRUE INTO v_created;

  SELECT * INTO v_transfer FROM public.business_wallet_transfers
  WHERE sender_business_id = v_sender_id AND idempotency_key = p_idempotency_key;
  IF v_transfer.recipient_business_id <> p_recipient_business_id
     OR v_transfer.amount_cop <> p_amount_cop THEN
    RAISE EXCEPTION 'Idempotency key already used with different transfer details';
  END IF;
  IF NOT COALESCE(v_created, FALSE) THEN
    RETURN jsonb_build_object('id', v_transfer.id, 'status', v_transfer.status, 'created', false);
  END IF;

  PERFORM w.id FROM public.wallets w
  WHERE w.business_id = v_sender_id ORDER BY w.id FOR UPDATE;
  SELECT COUNT(*) INTO v_wallet_count FROM public.wallets WHERE business_id = v_sender_id;
  IF v_wallet_count > 1 THEN
    UPDATE public.business_wallet_transfers SET status = 'cancelled',
      decision_reason = 'duplicate_wallets', decided_by = auth.uid(), decided_at = NOW()
    WHERE id = v_transfer.id AND status = 'pending';
    INSERT INTO public.business_wallet_transfer_reconciliation_cases (
      transfer_id, business_id, reason, observed_wallet_count, created_by
    ) VALUES (v_transfer.id, v_sender_id, 'duplicate_wallets', v_wallet_count, auth.uid())
    ON CONFLICT (transfer_id, business_id) WHERE transfer_id IS NOT NULL DO NOTHING;
    PERFORM public.write_system_audit_log(auth.uid(), 'canceló propuesta por wallets duplicadas',
      'business_wallet_transfer', v_transfer.id::TEXT,
      jsonb_build_object('business_id', v_sender_id, 'wallet_count', v_wallet_count));
    RETURN jsonb_build_object('id', v_transfer.id, 'status', 'cancelled',
      'created', true, 'reason', 'duplicate_wallets');
  END IF;
  SELECT id, COALESCE(balance, 0) INTO v_sender_wallet, v_balance
  FROM public.wallets WHERE business_id = v_sender_id ORDER BY id LIMIT 1;
  IF v_sender_wallet IS NULL THEN RAISE EXCEPTION 'Sender wallet not found'; END IF;
  IF COALESCE(v_created, FALSE) AND v_balance < p_amount_cop THEN
    RAISE EXCEPTION 'WALLET_INSUFFICIENT: transfer exceeds available balance';
  END IF;
  PERFORM public.write_system_audit_log(auth.uid(), 'propuso transferencia de saldo prepago',
    'business_wallet_transfer', v_transfer.id::TEXT,
    jsonb_build_object('sender_business_id', v_sender_id,
      'recipient_business_id', p_recipient_business_id, 'amount_cop', p_amount_cop));
  RETURN jsonb_build_object('id', v_transfer.id, 'status', v_transfer.status,
    'created', COALESCE(v_created, FALSE));
END;
$$;
REVOKE ALL ON FUNCTION public.propose_business_wallet_transfer(UUID, NUMERIC, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.propose_business_wallet_transfer(UUID, NUMERIC, UUID) TO authenticated;

CREATE OR REPLACE FUNCTION public.respond_business_wallet_transfer(p_transfer_id UUID, p_accept BOOLEAN)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_transfer public.business_wallet_transfers%ROWTYPE;
  v_sender_wallet UUID;
  v_recipient_wallet UUID;
  v_sender_wallet_count INTEGER;
  v_recipient_wallet_count INTEGER;
  v_balance NUMERIC(12,2);
BEGIN
  SELECT t.* INTO v_transfer
  FROM public.business_wallet_transfers t
  JOIN public.businesses b ON b.id = t.recipient_business_id AND b.profile_id = auth.uid()
  WHERE t.id = p_transfer_id
  FOR UPDATE OF t;
  IF NOT FOUND THEN RAISE EXCEPTION 'Transfer not found' USING ERRCODE = '42501'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role::TEXT = 'negocio') THEN
    RAISE EXCEPTION 'Business account required' USING ERRCODE = '42501';
  END IF;
  IF p_accept IS NULL THEN RAISE EXCEPTION 'An explicit accept or reject decision is required'; END IF;
  IF v_transfer.status IN ('accepted', 'declined', 'cancelled') THEN
    RETURN jsonb_build_object('id', v_transfer.id, 'status', v_transfer.status, 'applied', false);
  END IF;
  IF EXISTS (SELECT 1 FROM public.business_wallet_transfer_entries WHERE transfer_id = p_transfer_id) THEN
    RAISE EXCEPTION 'Transfer ledger is inconsistent; administrative review required';
  END IF;
  IF NOT p_accept THEN
    UPDATE public.business_wallet_transfers SET status = 'declined',
      decision_reason = 'recipient_declined', decided_by = auth.uid(), decided_at = NOW()
    WHERE id = p_transfer_id AND status = 'pending';
    PERFORM public.write_system_audit_log(auth.uid(), 'rechazó transferencia de saldo prepago',
      'business_wallet_transfer', p_transfer_id::TEXT,
      jsonb_build_object('sender_business_id', v_transfer.sender_business_id,
        'recipient_business_id', v_transfer.recipient_business_id, 'amount_cop', v_transfer.amount_cop));
    RETURN jsonb_build_object('id', p_transfer_id, 'status', 'declined', 'applied', false);
  END IF;

  PERFORM b.id FROM public.businesses b
  WHERE b.id IN (v_transfer.sender_business_id, v_transfer.recipient_business_id)
  ORDER BY b.id FOR UPDATE;
  PERFORM w.id FROM public.wallets w
  WHERE w.business_id IN (v_transfer.sender_business_id, v_transfer.recipient_business_id)
  ORDER BY w.business_id, w.id FOR UPDATE;
  SELECT COUNT(*) INTO v_sender_wallet_count FROM public.wallets
  WHERE business_id = v_transfer.sender_business_id;
  SELECT COUNT(*) INTO v_recipient_wallet_count FROM public.wallets
  WHERE business_id = v_transfer.recipient_business_id;
  IF v_sender_wallet_count > 1 OR v_recipient_wallet_count > 1
     OR v_sender_wallet_count = 0 THEN
    IF v_sender_wallet_count <> 1 THEN
      INSERT INTO public.business_wallet_transfer_reconciliation_cases (
        transfer_id, business_id, reason, observed_wallet_count, created_by
      ) VALUES (p_transfer_id, v_transfer.sender_business_id,
        CASE WHEN v_sender_wallet_count = 0 THEN 'missing_wallet' ELSE 'duplicate_wallets' END,
        v_sender_wallet_count, auth.uid())
      ON CONFLICT (transfer_id, business_id) WHERE transfer_id IS NOT NULL DO NOTHING;
    END IF;
    IF v_recipient_wallet_count > 1 THEN
      INSERT INTO public.business_wallet_transfer_reconciliation_cases (
        transfer_id, business_id, reason, observed_wallet_count, created_by
      ) VALUES (p_transfer_id, v_transfer.recipient_business_id, 'duplicate_wallets',
        v_recipient_wallet_count, auth.uid())
      ON CONFLICT (transfer_id, business_id) WHERE transfer_id IS NOT NULL DO NOTHING;
    END IF;
    UPDATE public.business_wallet_transfers SET status = 'cancelled',
      decision_reason = CASE
        WHEN v_sender_wallet_count > 1 OR v_recipient_wallet_count > 1 THEN 'duplicate_wallets'
        ELSE 'missing_wallet'
      END,
      decided_by = auth.uid(), decided_at = NOW()
    WHERE id = p_transfer_id AND status = 'pending';
    PERFORM public.write_system_audit_log(auth.uid(), 'canceló transferencia por inconsistencia de wallet',
      'business_wallet_transfer', p_transfer_id::TEXT,
      jsonb_build_object('sender_wallet_count', v_sender_wallet_count,
        'recipient_wallet_count', v_recipient_wallet_count));
    RETURN jsonb_build_object('id', p_transfer_id, 'status', 'cancelled',
      'applied', false, 'reason', 'wallet_reconciliation_required');
  END IF;

  IF v_recipient_wallet_count = 0 THEN
    INSERT INTO public.wallets (business_id, balance)
    VALUES (v_transfer.recipient_business_id, 0)
    RETURNING id INTO v_recipient_wallet;
  END IF;
  SELECT id, COALESCE(balance, 0) INTO v_sender_wallet, v_balance
  FROM public.wallets WHERE business_id = v_transfer.sender_business_id ORDER BY id LIMIT 1;
  IF v_balance < v_transfer.amount_cop THEN
    UPDATE public.business_wallet_transfers SET status = 'cancelled',
      decision_reason = 'insufficient_balance', decided_by = auth.uid(), decided_at = NOW()
    WHERE id = p_transfer_id AND status = 'pending';
    PERFORM public.write_system_audit_log(auth.uid(), 'canceló transferencia por saldo insuficiente',
      'business_wallet_transfer', p_transfer_id::TEXT,
      jsonb_build_object('sender_business_id', v_transfer.sender_business_id,
        'amount_cop', v_transfer.amount_cop, 'available_balance_cop', v_balance));
    RETURN jsonb_build_object('id', p_transfer_id, 'status', 'cancelled', 'applied', false,
      'reason', 'Sender balance is no longer sufficient');
  END IF;
  IF v_recipient_wallet IS NULL THEN
    SELECT id INTO v_recipient_wallet FROM public.wallets
    WHERE business_id = v_transfer.recipient_business_id ORDER BY id LIMIT 1;
  END IF;

  UPDATE public.wallets SET balance = balance - v_transfer.amount_cop, updated_at = NOW()
  WHERE id = v_sender_wallet AND balance >= v_transfer.amount_cop;
  IF NOT FOUND THEN RAISE EXCEPTION 'Sender balance changed during transfer'; END IF;
  UPDATE public.wallets SET balance = COALESCE(balance, 0) + v_transfer.amount_cop, updated_at = NOW()
  WHERE id = v_recipient_wallet;
  INSERT INTO public.business_wallet_transfer_entries (transfer_id, business_id, entry_type, amount_cop)
  VALUES (p_transfer_id, v_transfer.sender_business_id, 'transfer_debit', v_transfer.amount_cop),
         (p_transfer_id, v_transfer.recipient_business_id, 'transfer_credit', v_transfer.amount_cop);
  UPDATE public.business_wallet_transfers SET status = 'accepted', decided_by = auth.uid(), decided_at = NOW()
  WHERE id = p_transfer_id AND status = 'pending';
  PERFORM public.write_system_audit_log(auth.uid(), 'aceptó transferencia de saldo prepago',
    'business_wallet_transfer', p_transfer_id::TEXT,
    jsonb_build_object('sender_business_id', v_transfer.sender_business_id,
      'recipient_business_id', v_transfer.recipient_business_id, 'amount_cop', v_transfer.amount_cop));
  RETURN jsonb_build_object('id', p_transfer_id, 'status', 'accepted', 'applied', true);
END;
$$;
REVOKE ALL ON FUNCTION public.respond_business_wallet_transfer(UUID, BOOLEAN) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.respond_business_wallet_transfer(UUID, BOOLEAN) TO authenticated;

CREATE OR REPLACE FUNCTION public.cancel_business_wallet_transfer(p_transfer_id UUID)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_transfer public.business_wallet_transfers%ROWTYPE;
BEGIN
  SELECT t.* INTO v_transfer
  FROM public.business_wallet_transfers t
  JOIN public.businesses b ON b.id = t.sender_business_id AND b.profile_id = auth.uid()
  WHERE t.id = p_transfer_id
  FOR UPDATE OF t;
  IF NOT FOUND OR NOT EXISTS (
    SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role::TEXT = 'negocio'
  ) THEN
    RAISE EXCEPTION 'Transfer not found for this business' USING ERRCODE = '42501';
  END IF;
  IF v_transfer.status <> 'pending' THEN
    RETURN jsonb_build_object('id', p_transfer_id, 'status', v_transfer.status, 'applied', false);
  END IF;
  UPDATE public.business_wallet_transfers SET status = 'cancelled',
    decision_reason = 'sender_cancelled', decided_by = auth.uid(), decided_at = NOW()
  WHERE id = p_transfer_id AND status = 'pending';
  PERFORM public.write_system_audit_log(auth.uid(), 'canceló propuesta de transferencia de saldo',
    'business_wallet_transfer', p_transfer_id::TEXT,
    jsonb_build_object('recipient_business_id', v_transfer.recipient_business_id,
      'amount_cop', v_transfer.amount_cop));
  RETURN jsonb_build_object('id', p_transfer_id, 'status', 'cancelled', 'applied', true);
END;
$$;
REVOKE ALL ON FUNCTION public.cancel_business_wallet_transfer(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.cancel_business_wallet_transfer(UUID) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_resolve_business_wallet_transfer_case(
  p_case_id UUID, p_note TEXT
)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_case public.business_wallet_transfer_reconciliation_cases%ROWTYPE;
  v_wallet_count INTEGER;
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Administrator access required' USING ERRCODE = '42501'; END IF;
  IF NULLIF(BTRIM(p_note), '') IS NULL OR char_length(p_note) > 2000 THEN
    RAISE EXCEPTION 'A reconciliation note is required';
  END IF;
  SELECT * INTO v_case FROM public.business_wallet_transfer_reconciliation_cases
  WHERE id = p_case_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reconciliation case not found'; END IF;
  IF v_case.status = 'resolved' THEN
    IF v_case.admin_note = BTRIM(p_note) THEN RETURN; END IF;
    RAISE EXCEPTION 'Reconciliation case is already resolved';
  END IF;
  SELECT COUNT(*) INTO v_wallet_count FROM public.wallets WHERE business_id = v_case.business_id;
  IF v_wallet_count <> 1 THEN
    RAISE EXCEPTION 'Exactly one business wallet must exist before resolving this case';
  END IF;
  UPDATE public.business_wallet_transfer_reconciliation_cases SET status = 'resolved',
    admin_note = BTRIM(p_note), reviewed_by = auth.uid(), updated_at = NOW()
  WHERE id = p_case_id;
  PERFORM public.write_system_audit_log(auth.uid(), 'resolvió caso de conciliación de wallet',
    'business_wallet_transfer_case', p_case_id::TEXT,
    jsonb_build_object('transfer_id', v_case.transfer_id, 'business_id', v_case.business_id,
      'reason', v_case.reason, 'observed_wallet_count', v_case.observed_wallet_count,
      'current_wallet_count', v_wallet_count, 'note', BTRIM(p_note)));
END;
$$;
REVOKE ALL ON FUNCTION public.admin_resolve_business_wallet_transfer_case(UUID, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_resolve_business_wallet_transfer_case(UUID, TEXT) TO authenticated;


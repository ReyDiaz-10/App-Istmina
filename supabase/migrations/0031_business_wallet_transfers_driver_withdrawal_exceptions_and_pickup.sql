-- Preserve the current automatic bank payout path while enforcing configurable limits.
CREATE OR REPLACE FUNCTION public.claim_due_driver_payouts()
RETURNS SETOF JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, vault, pg_temp AS $$
DECLARE v_row RECORD; v_key TEXT; v_transaction_id UUID; v_reference TEXT;
BEGIN
  IF auth.role() IS DISTINCT FROM 'service_role' THEN RAISE EXCEPTION 'Service role required' USING ERRCODE = '42501'; END IF;
  SELECT decrypted_secret INTO v_key FROM vault.decrypted_secrets WHERE name = 'istmiya_payout_encryption_key';
  IF NULLIF(v_key, '') IS NULL THEN RAISE EXCEPTION 'Payout encryption is not configured'; END IF;
  FOR v_row IN
    SELECT w.id AS withdrawal_id, w.driver_id, w.amount_cop, d.profile_id, p.full_name, u.email,
      a.bank_id, a.bank_name, a.account_type, a.account_number_last4, a.legal_id_type,
      extensions.pgp_sym_decrypt(a.legal_id_ciphertext, v_key) AS legal_id,
      extensions.pgp_sym_decrypt(a.account_number_ciphertext, v_key) AS account_number
    FROM public.driver_withdrawals w
    JOIN public.drivers d ON d.id = w.driver_id JOIN public.profiles p ON p.id = d.profile_id
    JOIN auth.users u ON u.id = p.id JOIN public.payout_accounts a ON a.profile_id = p.id
    CROSS JOIN public.driver_payout_settings settings
    WHERE w.status = 'scheduled' AND w.scheduled_for <= NOW()
      AND w.amount_cop BETWEEN GREATEST(settings.minimum_amount_cop, 20000) AND settings.maximum_amount_cop
      AND 'bank_account' = ANY(settings.supported_methods)
      AND NOT EXISTS (SELECT 1 FROM public.payout_transactions pt WHERE pt.withdrawal_id = w.id)
      AND NOT EXISTS (SELECT 1 FROM public.driver_withdrawal_exceptions e
        WHERE e.withdrawal_id = w.id AND e.status IN ('open', 'under_review'))
    ORDER BY w.scheduled_for LIMIT 100 FOR UPDATE OF w SKIP LOCKED
  LOOP
    v_reference := 'istmiya-' || REPLACE(gen_random_uuid()::TEXT, '-', '');
    INSERT INTO public.payout_transactions (
      withdrawal_id, driver_id, profile_id, amount_cop, reference, status,
      bank_name, account_type, account_number_last4
    ) VALUES (v_row.withdrawal_id, v_row.driver_id, v_row.profile_id, v_row.amount_cop,
      v_reference, 'processing', v_row.bank_name, v_row.account_type, v_row.account_number_last4)
    RETURNING id INTO v_transaction_id;
    UPDATE public.driver_withdrawals SET status = 'processing' WHERE id = v_row.withdrawal_id;
    RETURN NEXT jsonb_build_object('payout_transaction_id', v_transaction_id,
      'withdrawal_id', v_row.withdrawal_id, 'profile_id', v_row.profile_id,
      'full_name', v_row.full_name, 'email', v_row.email, 'amount_cop', v_row.amount_cop,
      'reference', v_reference, 'bank_id', v_row.bank_id, 'bank_name', v_row.bank_name,
      'account_type', v_row.account_type, 'account_number', v_row.account_number,
      'legal_id_type', v_row.legal_id_type, 'legal_id', v_row.legal_id);
  END LOOP;
  -- Missing accounts remain reserved and are escalated for administrative resolution.
  WITH inserted AS (
   INSERT INTO public.driver_withdrawal_exceptions (
    withdrawal_id, driver_id, reason, evidence_urls, verification_provider,
    verification_reference, status
   )
  SELECT w.id, w.driver_id, 'missing_account', ARRAY['system/missing-account'],
    'Automatic payout preflight', 'account-not-configured', 'open'
  FROM public.driver_withdrawals w
  CROSS JOIN public.driver_payout_settings settings
  WHERE w.status = 'scheduled' AND w.scheduled_for <= NOW()
    AND w.amount_cop >= GREATEST(settings.minimum_amount_cop, 20000)
    AND w.amount_cop <= settings.maximum_amount_cop
    AND NOT EXISTS (SELECT 1 FROM public.payout_accounts a
      JOIN public.drivers d ON d.profile_id = a.profile_id WHERE d.id = w.driver_id)
    AND NOT EXISTS (SELECT 1 FROM public.driver_withdrawal_exceptions e
      WHERE e.withdrawal_id = w.id AND e.reason = 'missing_account'
        AND e.status IN ('open', 'under_review', 'rejected'))
   ON CONFLICT DO NOTHING RETURNING withdrawal_id
  )
  UPDATE public.driver_withdrawals w SET
    failure_reason = 'Missing payout account; administrative review required'
  WHERE w.status = 'scheduled' AND w.id IN (SELECT withdrawal_id FROM inserted);
  WITH inserted AS (
    INSERT INTO public.driver_withdrawal_exceptions (
      withdrawal_id, driver_id, reason, evidence_urls, verification_provider, verification_reference, status
    )
    SELECT w.id, w.driver_id, 'outside_limits', ARRAY['system/payout-limit-review'],
      'Automatic payout preflight', 'amount-outside-configured-limits:' || w.amount_cop::TEXT, 'open'
    FROM public.driver_withdrawals w CROSS JOIN public.driver_payout_settings settings
    WHERE w.status = 'scheduled' AND w.scheduled_for <= NOW()
      AND (w.amount_cop < GREATEST(settings.minimum_amount_cop, 20000)
        OR w.amount_cop > settings.maximum_amount_cop)
      AND NOT EXISTS (SELECT 1 FROM public.driver_withdrawal_exceptions e
        WHERE e.withdrawal_id = w.id AND e.reason = 'outside_limits'
          AND e.status IN ('open', 'under_review', 'rejected'))
    ON CONFLICT DO NOTHING RETURNING withdrawal_id
  )
  UPDATE public.driver_withdrawals w SET
    failure_reason = 'Withdrawal amount is outside configured payout limits; administrative review required'
  WHERE w.status = 'scheduled' AND w.id IN (SELECT withdrawal_id FROM inserted);
END;
$$;
REVOKE ALL ON FUNCTION public.claim_due_driver_payouts() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_due_driver_payouts() TO service_role;


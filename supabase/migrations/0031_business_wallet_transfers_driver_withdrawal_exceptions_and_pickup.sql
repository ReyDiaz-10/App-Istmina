CREATE OR REPLACE FUNCTION public.admin_record_withdrawal_result(
  p_withdrawal_id UUID,
  p_status TEXT,
  p_provider TEXT DEFAULT NULL,
  p_provider_reference TEXT DEFAULT NULL,
  p_failure_reason TEXT DEFAULT NULL
)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_row public.driver_withdrawals%ROWTYPE;
BEGIN
  IF NOT public.is_superadmin() THEN
    RAISE EXCEPTION 'SuperAdmin access required' USING ERRCODE = '42501';
  END IF;
  IF p_status IS DISTINCT FROM 'processing' THEN
    RAISE EXCEPTION 'Final withdrawal states can only be set by the verified Wompi payout webhook';
  END IF;
  UPDATE public.driver_withdrawals SET
    status = 'processing',
    provider = COALESCE(NULLIF(BTRIM(p_provider), ''), provider),
    provider_reference = COALESCE(NULLIF(BTRIM(p_provider_reference), ''), provider_reference),
    failure_reason = NULL
  WHERE id = p_withdrawal_id AND status IN ('scheduled', 'processing')
  RETURNING * INTO v_row;
  IF NOT FOUND THEN RAISE EXCEPTION 'Withdrawal not found or already final'; END IF;
  PERFORM public.write_system_audit_log(auth.uid(), 'registró retiro en proceso',
    'withdrawal', v_row.id::TEXT,
    jsonb_build_object('amount_cop', v_row.amount_cop, 'status', v_row.status,
      'driver_id', v_row.driver_id, 'provider_reference', v_row.provider_reference,
      'admin_note', LEFT(NULLIF(BTRIM(p_failure_reason), ''), 500)));
END;
$$;
REVOKE ALL ON FUNCTION public.admin_record_withdrawal_result(UUID, TEXT, TEXT, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_record_withdrawal_result(UUID, TEXT, TEXT, TEXT, TEXT) TO authenticated;

CREATE TABLE IF NOT EXISTS public.driver_withdrawal_exceptions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  withdrawal_id UUID REFERENCES public.driver_withdrawals(id) ON DELETE RESTRICT,
  driver_id UUID NOT NULL REFERENCES public.drivers(id) ON DELETE RESTRICT,
  reason TEXT NOT NULL CHECK (reason IN ('missing_account', 'not_received', 'outside_limits')),

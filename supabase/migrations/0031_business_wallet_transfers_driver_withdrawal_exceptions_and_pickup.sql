CREATE OR REPLACE FUNCTION public.driver_payout_summary()
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_driver_id UUID; v_earned NUMERIC(12,2); v_withdrawn NUMERIC(12,2); v_reserved NUMERIC(12,2); v_summary JSONB;
BEGIN
  SELECT d.id INTO v_driver_id FROM public.drivers d
  JOIN public.profiles p ON p.id = d.profile_id
  WHERE d.profile_id = auth.uid() AND p.role::TEXT = 'repartidor';
  IF v_driver_id IS NULL THEN RAISE EXCEPTION 'Perfil de repartidor no encontrado' USING ERRCODE = '42501'; END IF;
  SELECT COALESCE(SUM(amount_cop),0) INTO v_earned FROM public.driver_wallet_entries WHERE driver_id = v_driver_id;
  SELECT COALESCE(SUM(amount_cop) FILTER (WHERE status = 'paid'),0),
    COALESCE(SUM(amount_cop) FILTER (WHERE status IN ('scheduled','processing')),0)
    INTO v_withdrawn, v_reserved FROM public.driver_withdrawals WHERE driver_id = v_driver_id;
  SELECT jsonb_build_object(
    'available_balance', v_earned - v_withdrawn - v_reserved,
    'reserved_balance', v_reserved, 'withdrawn_balance', v_withdrawn,
    'threshold_cop', (SELECT minimum_amount_cop FROM public.driver_payout_settings WHERE id),
    'maximum_amount_cop', (SELECT maximum_amount_cop FROM public.driver_payout_settings WHERE id),
    'payout_account', (SELECT jsonb_build_object('bank_name', bank_name, 'account_type', account_type,
      'account_number_last4', account_number_last4, 'updated_at', updated_at) FROM public.payout_accounts WHERE profile_id = auth.uid()),
    'scheduled', COALESCE((SELECT jsonb_agg(jsonb_build_object(
      'id', w.id, 'amount_cop', w.amount_cop, 'scheduled_for', w.scheduled_for, 'status', w.status,
      'payout_status', t.status, 'bank_name', COALESCE(t.bank_name, a.bank_name),
      'account_number_last4', COALESCE(t.account_number_last4, a.account_number_last4)
    ) ORDER BY w.scheduled_for) FROM public.driver_withdrawals w
      LEFT JOIN public.payout_transactions t ON t.withdrawal_id = w.id
      LEFT JOIN public.payout_accounts a ON a.profile_id = auth.uid()
      WHERE w.driver_id = v_driver_id AND w.status IN ('scheduled','processing')), '[]'::JSONB),
    'history', COALESCE((SELECT jsonb_agg(jsonb_build_object(
      'id', w.id, 'amount_cop', w.amount_cop, 'paid_at', w.paid_at, 'status', w.status,
      'provider_reference', t.reference, 'provider_payout_id', t.provider_payout_id,
      'bank_name', COALESCE(t.bank_name, a.bank_name),
      'account_number_last4', COALESCE(t.account_number_last4, a.account_number_last4)
    ) ORDER BY COALESCE(w.paid_at, w.created_at) DESC) FROM public.driver_withdrawals w
      LEFT JOIN public.payout_transactions t ON t.withdrawal_id = w.id
      LEFT JOIN public.payout_accounts a ON a.profile_id = auth.uid()
      WHERE w.driver_id = v_driver_id AND w.status IN ('paid','failed','cancelled')), '[]'::JSONB),
    'open_exceptions', COALESCE((SELECT jsonb_agg(jsonb_build_object(
      'id', e.id, 'withdrawal_id', e.withdrawal_id, 'reason', e.reason, 'status', e.status,
      'verification_provider', e.verification_provider, 'verification_reference', e.verification_reference,
      'created_at', e.created_at
    ) ORDER BY e.created_at DESC) FROM public.driver_withdrawal_exceptions e
      WHERE e.driver_id = v_driver_id AND e.status IN ('open','under_review')), '[]'::JSONB),
    'withdrawal_exceptions', COALESCE((SELECT jsonb_agg(jsonb_build_object(
      'id', e.id, 'withdrawal_id', e.withdrawal_id, 'reason', e.reason, 'status', e.status,
      'verification_provider', e.verification_provider, 'verification_reference', e.verification_reference,
      'created_at', e.created_at
    ) ORDER BY e.created_at DESC) FROM (
      SELECT * FROM public.driver_withdrawal_exceptions
      WHERE driver_id = v_driver_id ORDER BY created_at DESC LIMIT 20
    ) e), '[]'::JSONB)
  ) INTO v_summary;
  RETURN v_summary;
END;
$$;
REVOKE ALL ON FUNCTION public.driver_payout_summary() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.driver_payout_summary() TO authenticated;

CREATE OR REPLACE FUNCTION public.submit_driver_withdrawal_exception(
  p_withdrawal_id UUID, p_reason TEXT, p_evidence_urls TEXT[],
  p_verification_provider TEXT, p_verification_reference TEXT
)
RETURNS UUID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_driver_id UUID;
  v_id UUID;
  v_status TEXT;
  v_evidence_count INTEGER;
BEGIN
  SELECT d.id INTO v_driver_id
  FROM public.drivers d JOIN public.profiles p ON p.id = d.profile_id
  WHERE d.profile_id = auth.uid() AND p.role::TEXT = 'repartidor'
  FOR SHARE OF d;
  IF v_driver_id IS NULL OR p_reason IS NULL
     OR p_reason NOT IN ('missing_account', 'not_received', 'outside_limits')
     OR p_evidence_urls IS NULL OR cardinality(p_evidence_urls) NOT BETWEEN 1 AND 5
     OR EXISTS (
       SELECT 1 FROM unnest(p_evidence_urls) AS evidence(path)
       WHERE evidence.path !~ ('^' || auth.uid()::TEXT || '/withdrawal-exceptions/[^[:space:]]+$')
          OR NOT EXISTS (
            SELECT 1 FROM storage.objects object
            WHERE object.bucket_id = 'driver-documents' AND object.name = evidence.path
          )
     )
     OR NULLIF(BTRIM(p_verification_provider), '') IS NULL
     OR NULLIF(BTRIM(p_verification_reference), '') IS NULL THEN
    RAISE EXCEPTION 'Evidence and bank/platform verification are required';
  END IF;
  SELECT COUNT(DISTINCT evidence.path) INTO v_evidence_count
  FROM unnest(p_evidence_urls) AS evidence(path);
  IF v_evidence_count <> cardinality(p_evidence_urls) THEN
    RAISE EXCEPTION 'Each evidence attachment must be unique';
  END IF;
  IF p_withdrawal_id IS NOT NULL THEN
    SELECT status INTO v_status FROM public.driver_withdrawals
    WHERE id = p_withdrawal_id AND driver_id = v_driver_id FOR UPDATE;
    IF NOT FOUND OR v_status NOT IN ('scheduled', 'processing', 'paid', 'failed') THEN
      RAISE EXCEPTION 'Withdrawal is not available for exception review';
    END IF;
    IF p_reason = 'outside_limits' AND NOT EXISTS (
      SELECT 1 FROM public.driver_withdrawal_exceptions e WHERE e.withdrawal_id = p_withdrawal_id
        AND e.driver_id = v_driver_id AND e.reason = 'outside_limits' AND e.status IN ('open', 'under_review')
    ) THEN RAISE EXCEPTION 'A limit review must already exist'; END IF;
  END IF;
  IF p_reason = 'missing_account' THEN
    IF EXISTS (SELECT 1 FROM public.payout_accounts WHERE profile_id = auth.uid()) THEN
      RAISE EXCEPTION 'A missing account exception requires no configured account';
    END IF;
  ELSIF p_withdrawal_id IS NULL THEN
    RAISE EXCEPTION 'A withdrawal is required for this exception type';
  END IF;
  IF p_withdrawal_id IS NOT NULL THEN
    INSERT INTO public.driver_withdrawal_exceptions (
      withdrawal_id, driver_id, reason, evidence_urls, verification_provider, verification_reference
    ) VALUES (
      p_withdrawal_id, v_driver_id, p_reason, p_evidence_urls,
      LEFT(BTRIM(p_verification_provider), 100), LEFT(BTRIM(p_verification_reference), 160)
    ) ON CONFLICT (withdrawal_id, driver_id)
      WHERE withdrawal_id IS NOT NULL AND status IN ('open', 'under_review')
      DO UPDATE SET evidence_urls = EXCLUDED.evidence_urls,
        verification_provider = EXCLUDED.verification_provider,
        verification_reference = EXCLUDED.verification_reference,
        reason = EXCLUDED.reason, updated_at = NOW()
    RETURNING id INTO v_id;
  ELSE
    INSERT INTO public.driver_withdrawal_exceptions (
      withdrawal_id, driver_id, reason, evidence_urls, verification_provider, verification_reference
    ) VALUES (NULL, v_driver_id, p_reason, p_evidence_urls,
      LEFT(BTRIM(p_verification_provider), 100), LEFT(BTRIM(p_verification_reference), 160))
    ON CONFLICT (driver_id)
      WHERE withdrawal_id IS NULL AND reason = 'missing_account' AND status IN ('open', 'under_review')
      DO UPDATE SET evidence_urls = EXCLUDED.evidence_urls,
        verification_provider = EXCLUDED.verification_provider,
        verification_reference = EXCLUDED.verification_reference, updated_at = NOW()
    RETURNING id INTO v_id;
  END IF;
  PERFORM public.write_system_audit_log(auth.uid(), 'envió excepción de retiro con evidencia',
    'driver_withdrawal_exception', v_id::TEXT,
    jsonb_build_object('withdrawal_id', p_withdrawal_id, 'reason', p_reason,
      'evidence_count', cardinality(p_evidence_urls),
      'verification_provider', BTRIM(p_verification_provider),
      'verification_reference', BTRIM(p_verification_reference)));
  RETURN v_id;
END;
$$;
REVOKE ALL ON FUNCTION public.submit_driver_withdrawal_exception(UUID, TEXT, TEXT[], TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.submit_driver_withdrawal_exception(UUID, TEXT, TEXT[], TEXT, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_review_driver_withdrawal_exception(
  p_exception_id UUID, p_status TEXT, p_note TEXT
)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_exception public.driver_withdrawal_exceptions%ROWTYPE;
  v_resolvable BOOLEAN := FALSE;
BEGIN
  IF NOT public.is_admin() THEN RAISE EXCEPTION 'Administrator access required' USING ERRCODE = '42501'; END IF;
  IF p_status IS NULL OR p_status NOT IN ('under_review', 'resolved', 'rejected')
     OR NULLIF(BTRIM(p_note), '') IS NULL
     OR char_length(p_note) > 2000 THEN RAISE EXCEPTION 'Invalid exception review'; END IF;
  SELECT * INTO v_exception FROM public.driver_withdrawal_exceptions WHERE id = p_exception_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Exception not found'; END IF;
  IF v_exception.status IN ('resolved', 'rejected') THEN
    IF v_exception.status = p_status AND v_exception.admin_note = BTRIM(p_note) THEN RETURN; END IF;
    RAISE EXCEPTION 'Exception is already final';
  END IF;
  IF p_status = 'resolved' THEN
    IF v_exception.reason = 'missing_account' THEN
      SELECT EXISTS (
        SELECT 1 FROM public.payout_accounts a
        JOIN public.drivers d ON d.profile_id = a.profile_id
        WHERE d.id = v_exception.driver_id
      ) INTO v_resolvable;
    ELSIF v_exception.reason = 'outside_limits' THEN
      SELECT EXISTS (
        SELECT 1 FROM public.driver_withdrawals w
        JOIN public.drivers d ON d.id = w.driver_id
        JOIN public.payout_accounts a ON a.profile_id = d.profile_id
        CROSS JOIN public.driver_payout_settings settings
        WHERE w.id = v_exception.withdrawal_id AND w.status = 'scheduled'
          AND w.amount_cop BETWEEN GREATEST(settings.minimum_amount_cop, 20000)
            AND settings.maximum_amount_cop
      ) INTO v_resolvable;
    ELSE
      SELECT EXISTS (
        SELECT 1 FROM public.driver_withdrawals w
        JOIN public.payout_transactions t ON t.withdrawal_id = w.id
        WHERE w.id = v_exception.withdrawal_id AND t.provider = 'wompi'
          AND t.status IN ('success', 'failed')
      ) INTO v_resolvable;
    END IF;
    IF NOT v_resolvable THEN
      RAISE EXCEPTION 'The reported condition has not been verified by the required account or provider record';
    END IF;
  END IF;
  UPDATE public.driver_withdrawal_exceptions SET status = p_status, admin_note = BTRIM(p_note),
    reviewed_by = auth.uid(), updated_at = NOW() WHERE id = p_exception_id;
  PERFORM public.write_system_audit_log(auth.uid(), 'revisó excepción de retiro',
    'driver_withdrawal_exception', p_exception_id::TEXT,
    jsonb_build_object('previous_status', v_exception.status, 'status', p_status,
      'withdrawal_id', v_exception.withdrawal_id, 'reason', v_exception.reason,
      'verification_provider', v_exception.verification_provider,
      'verification_reference', v_exception.verification_reference,
      'note', BTRIM(p_note)));
END;
$$;
REVOKE ALL ON FUNCTION public.admin_review_driver_withdrawal_exception(UUID, TEXT, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_review_driver_withdrawal_exception(UUID, TEXT, TEXT) TO authenticated;


-- Keep the existing order-creation RPC unchanged; this additional RPC creates a store pickup.
CREATE OR REPLACE FUNCTION public.create_pickup_order(
  p_business_id UUID, p_items JSONB, p_idempotency_key UUID
)
RETURNS UUID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions, pg_temp AS $$
DECLARE
  v_client_id UUID := auth.uid();
  v_role TEXT;
  v_item JSONB;
  v_option RECORD;
  v_option_ids JSONB;
  v_product_id UUID;
  v_quantity INTEGER;
  v_price NUMERIC(12,2);
  v_option_delta NUMERIC(12,2);
  v_subtotal NUMERIC(12,2) := 0;
  v_subscribed BOOLEAN;
  v_wallet_balance NUMERIC(12,2);
  v_wallet_count INTEGER;
  v_inventory_enabled BOOLEAN;
  v_product_available BOOLEAN;
  v_stock_quantity INTEGER;
  v_reserved_quantity INTEGER;
  v_order_id UUID;
  v_order_item_id UUID;
  v_pickup_code TEXT;
  v_delivery_code TEXT;
  v_existing_order UUID;
  v_existing_fingerprint TEXT;
  v_request_fingerprint TEXT;
  v_business_status TEXT;
  v_pickup_enabled BOOLEAN;
BEGIN
  SELECT role::TEXT INTO v_role FROM public.profiles WHERE id = v_client_id;
  IF v_client_id IS NULL OR v_role IS DISTINCT FROM 'cliente' THEN
    RAISE EXCEPTION 'Only clients can place pickup orders' USING ERRCODE = '42501';
  END IF;
  IF p_business_id IS NULL OR p_idempotency_key IS NULL THEN
    RAISE EXCEPTION 'Business and idempotency key are required';
  END IF;
  v_request_fingerprint := encode(extensions.digest(p_items::TEXT, 'sha256'), 'hex');
  PERFORM pg_advisory_xact_lock(hashtextextended(
    v_client_id::TEXT || ':' || p_business_id::TEXT || ':' || p_idempotency_key::TEXT, 0));
  SELECT order_id, request_fingerprint
    INTO v_existing_order, v_existing_fingerprint
  FROM public.pickup_order_idempotency
  WHERE client_id = v_client_id AND business_id = p_business_id
    AND idempotency_key = p_idempotency_key;
  IF FOUND THEN
    IF v_existing_fingerprint IS DISTINCT FROM v_request_fingerprint THEN
      RAISE EXCEPTION 'Idempotency key was already used with different order details';
    END IF;
    IF v_existing_order IS NULL THEN
      RAISE EXCEPTION 'Pickup order idempotency record is incomplete; administrative review required';
    END IF;
    RETURN v_existing_order;
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN
    RAISE EXCEPTION 'Invalid order item list';
  END IF;
  SELECT status::TEXT, pickup_enabled INTO v_business_status, v_pickup_enabled
  FROM public.businesses WHERE id = p_business_id FOR SHARE;
  IF NOT FOUND OR v_business_status <> 'activo' OR NOT v_pickup_enabled THEN
    RAISE EXCEPTION 'Business pickup is unavailable';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.get_business_operating_status(p_business_id) operating_status
    WHERE COALESCE((operating_status->>'is_open')::BOOLEAN, FALSE)
       OR NOT COALESCE((operating_status->>'configured')::BOOLEAN, FALSE)
  ) THEN
    RAISE EXCEPTION 'Business is not accepting orders at this time';
  END IF;

  PERFORM product.id FROM public.products product
  JOIN (
    SELECT DISTINCT (item.value->>'product_id')::UUID AS product_id
    FROM jsonb_array_elements(p_items) AS item(value)
  ) requested ON requested.product_id = product.id
  WHERE product.business_id = p_business_id
  ORDER BY product.id FOR UPDATE OF product;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    BEGIN
      v_product_id := (v_item->>'product_id')::UUID;
      v_quantity := (v_item->>'quantity')::INTEGER;
    EXCEPTION
      WHEN invalid_text_representation OR numeric_value_out_of_range THEN
        RAISE EXCEPTION 'Invalid product or quantity in pickup order';
    END;
    IF v_quantity NOT BETWEEN 1 AND 50 THEN
      RAISE EXCEPTION 'Pickup order quantity must be between 1 and 50';
    END IF;
    SELECT price, is_available, inventory_enabled, stock_quantity, reserved_quantity
      INTO v_price, v_product_available, v_inventory_enabled, v_stock_quantity, v_reserved_quantity
    FROM public.products
    WHERE id = v_product_id AND business_id = p_business_id;
    IF NOT FOUND OR NOT v_product_available OR v_price IS NULL OR v_price <= 0 THEN
      RAISE EXCEPTION 'Product is unavailable for this business';
    END IF;
    IF v_inventory_enabled AND (
      v_stock_quantity IS NULL OR v_reserved_quantity IS NULL
      OR v_stock_quantity - v_reserved_quantity < v_quantity
    ) THEN
      RAISE EXCEPTION 'INSUFFICIENT_STOCK: Product inventory is insufficient';
    END IF;

    PERFORM po.id FROM public.product_options po
    WHERE po.product_id = v_product_id ORDER BY po.id FOR SHARE OF po;
    v_option_ids := COALESCE(v_item->'option_ids', '[]'::JSONB);
    IF jsonb_typeof(v_option_ids) <> 'array' OR jsonb_array_length(v_option_ids) > 20 THEN
      RAISE EXCEPTION 'Invalid product options';
    END IF;
    IF EXISTS (
      SELECT 1 FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
      GROUP BY option_id HAVING COUNT(*) > 1
    ) THEN
      RAISE EXCEPTION 'A product option cannot be selected more than once';
    END IF;
    IF EXISTS (
      SELECT po.option_group
      FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
      JOIN public.product_options po ON po.id = selected.option_id::UUID
      WHERE po.product_id = v_product_id AND po.option_type = 'variant' AND po.is_available
      GROUP BY po.option_group HAVING COUNT(*) > 1
    ) THEN
      RAISE EXCEPTION 'Select only one variant per option group';
    END IF;
    IF EXISTS (
      SELECT 1 FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
      WHERE NOT EXISTS (
        SELECT 1 FROM public.product_options po
        WHERE po.id = selected.option_id::UUID
          AND po.product_id = v_product_id AND po.business_id = p_business_id
          AND po.is_available
      )
    ) THEN
      RAISE EXCEPTION 'A selected product option is unavailable';
    END IF;
    IF EXISTS (
      SELECT required_option.option_group
      FROM public.product_options required_option
      WHERE required_option.product_id = v_product_id
        AND required_option.business_id = p_business_id
        AND required_option.is_available AND required_option.is_required
      GROUP BY required_option.option_group
      HAVING NOT EXISTS (
        SELECT 1 FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
        JOIN public.product_options selected_option ON selected_option.id = selected.option_id::UUID
        WHERE selected_option.product_id = v_product_id
          AND selected_option.option_group = required_option.option_group
          AND selected_option.is_available
      )
    ) THEN
      RAISE EXCEPTION 'A required product option has not been selected';
    END IF;

    SELECT COALESCE(SUM(po.price_delta), 0) INTO v_option_delta
    FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
    JOIN public.product_options po ON po.id = selected.option_id::UUID
    WHERE po.product_id = v_product_id AND po.business_id = p_business_id AND po.is_available;
    v_subtotal := v_subtotal + (v_price + v_option_delta) * v_quantity;
  END LOOP;

  SELECT EXISTS (SELECT 1 FROM public.subscriptions WHERE business_id = p_business_id AND is_active
    AND start_date <= CURRENT_DATE AND end_date >= CURRENT_DATE) INTO v_subscribed;
  IF NOT v_subscribed THEN
    PERFORM id FROM public.wallets WHERE business_id = p_business_id ORDER BY id FOR UPDATE;
    SELECT COUNT(*) INTO v_wallet_count FROM public.wallets WHERE business_id = p_business_id;
    IF v_wallet_count <> 1 THEN
      RAISE EXCEPTION 'Business wallet is missing or requires reconciliation';
    END IF;
    SELECT COALESCE(balance, 0) INTO v_wallet_balance
    FROM public.wallets WHERE business_id = p_business_id;
    IF v_wallet_balance < ROUND(v_subtotal * 0.10, 2) THEN
      RAISE EXCEPTION 'WALLET_INSUFFICIENT: Business wallet cannot cover the 10%% commission';
    END IF;
  END IF;

  INSERT INTO public.orders (client_id, business_id, total_amount, product_subtotal_cop,
    delivery_fee_cop, distance_meters, delivery_latitude, delivery_longitude, delivery_address,
    delivery_instructions, payment_method, status, delivery_mode)
  VALUES (v_client_id, p_business_id, v_subtotal, v_subtotal, 0, 0, NULL, NULL,
    'Retiro en tienda', NULL, 'wompi', 'pendiente', 'pickup') RETURNING id INTO v_order_id;
  INSERT INTO public.pickup_order_idempotency (
    client_id, business_id, idempotency_key, request_fingerprint, order_id
  ) VALUES (v_client_id, p_business_id, p_idempotency_key, v_request_fingerprint, v_order_id);

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_product_id := (v_item->>'product_id')::UUID;
    v_quantity := (v_item->>'quantity')::INTEGER;
    v_option_ids := COALESCE(v_item->'option_ids', '[]'::JSONB);
    SELECT price, inventory_enabled INTO v_price, v_inventory_enabled
    FROM public.products WHERE id = v_product_id;
    SELECT COALESCE(SUM(po.price_delta), 0) INTO v_option_delta
    FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
    JOIN public.product_options po ON po.id = selected.option_id::UUID
    WHERE po.product_id = v_product_id AND po.business_id = p_business_id AND po.is_available;

    INSERT INTO public.order_items (order_id, product_id, quantity, unit_price)
    VALUES (v_order_id, v_product_id, v_quantity, v_price + v_option_delta)
    RETURNING id INTO v_order_item_id;
    FOR v_option IN
      SELECT po.id, po.option_group, po.name, po.price_delta
      FROM jsonb_array_elements_text(v_option_ids) selected(option_id)
      JOIN public.product_options po ON po.id = selected.option_id::UUID
      WHERE po.product_id = v_product_id AND po.business_id = p_business_id AND po.is_available
    LOOP
      INSERT INTO public.order_item_options (
        order_item_id, product_option_id, option_group, name, price_delta
      ) VALUES (
        v_order_item_id, v_option.id, v_option.option_group, v_option.name, v_option.price_delta
      );
    END LOOP;

    IF v_inventory_enabled THEN
      UPDATE public.products
      SET reserved_quantity = reserved_quantity + v_quantity
      WHERE id = v_product_id AND inventory_enabled
        AND stock_quantity IS NOT NULL
        AND stock_quantity - reserved_quantity >= v_quantity;
      IF NOT FOUND THEN RAISE EXCEPTION 'INSUFFICIENT_STOCK'; END IF;
      INSERT INTO public.order_inventory_reservations (order_id, product_id, quantity)
      VALUES (v_order_id, v_product_id, v_quantity)
      ON CONFLICT (order_id, product_id) DO UPDATE SET
        quantity = public.order_inventory_reservations.quantity + EXCLUDED.quantity;
    END IF;
  END LOOP;

  v_pickup_code := substr(translate(md5(gen_random_uuid()::TEXT), 'abcdef', '123456'), 1, 6);
  v_delivery_code := substr(translate(md5(gen_random_uuid()::TEXT), 'abcdef', '123456'), 1, 6);
  INSERT INTO public.order_verification_secrets (order_id, pickup_code, pickup_code_hash, delivery_code, delivery_code_hash)
  VALUES (
    v_order_id, v_pickup_code, encode(extensions.digest(v_pickup_code, 'sha256'), 'hex'),
    v_delivery_code, encode(extensions.digest(v_delivery_code, 'sha256'), 'hex')
  );
  RETURN v_order_id;
END;
$$;
REVOKE ALL ON FUNCTION public.create_pickup_order(UUID, JSONB, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_pickup_order(UUID, JSONB, UUID) TO authenticated;

CREATE OR REPLACE FUNCTION public.apply_wompi_payment(
  p_transaction_id TEXT,
  p_payment_link_id TEXT,
  p_amount_in_cents BIGINT,
  p_currency TEXT,
  p_status TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_link public.wompi_payment_links%ROWTYPE;
  v_transaction public.wompi_transactions%ROWTYPE;
  v_order_status TEXT;
  v_subscription_id UUID;
  v_subscription_end DATE;
BEGIN
  IF auth.role() IS DISTINCT FROM 'service_role' THEN
    RAISE EXCEPTION 'Service role required' USING ERRCODE = '42501';
  END IF;
  IF p_transaction_id IS NULL OR p_payment_link_id IS NULL
     OR p_amount_in_cents IS NULL OR p_currency IS NULL OR p_status IS NULL THEN
    RETURN FALSE;
  END IF;

  SELECT * INTO v_link
  FROM public.wompi_payment_links
  WHERE payment_link_id = p_payment_link_id
  FOR UPDATE;
  IF NOT FOUND THEN RETURN FALSE; END IF;
  IF p_amount_in_cents <> v_link.amount_in_cents OR p_currency <> 'COP' THEN
    RAISE EXCEPTION 'Wompi payment amount or currency does not match';
  END IF;

  INSERT INTO public.wompi_transactions (
    transaction_id, payment_link_id, order_id, amount_in_cents, status, created_at, updated_at
  )
  VALUES (
    p_transaction_id, p_payment_link_id, v_link.order_id, p_amount_in_cents, p_status, NOW(), NOW()
  )
  ON CONFLICT (transaction_id) DO UPDATE
  SET status = CASE
        WHEN public.wompi_transactions.applied_at IS NOT NULL
          AND EXCLUDED.status <> 'APPROVED'
        THEN public.wompi_transactions.status
        ELSE EXCLUDED.status
      END,
      updated_at = NOW()
  WHERE public.wompi_transactions.payment_link_id = EXCLUDED.payment_link_id
  RETURNING * INTO v_transaction;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Wompi transaction is already linked to another payment';
  END IF;

  UPDATE public.wompi_payment_links
  SET status = LOWER(p_status)
  WHERE payment_link_id = p_payment_link_id;

  IF v_link.purpose = 'order' AND p_status IN ('DECLINED', 'ERROR', 'VOIDED') THEN
    UPDATE public.order_payment_attempts
    SET status = 'failed', updated_at = NOW()
    WHERE order_id = v_link.order_id AND payment_link_id = p_payment_link_id;
  END IF;

  IF p_status <> 'APPROVED' OR v_transaction.applied_at IS NOT NULL THEN
    RETURN FALSE;
  END IF;

  IF v_link.purpose = 'order' THEN
    SELECT status::TEXT INTO v_order_status
    FROM public.orders WHERE id = v_link.order_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Wompi order not found'; END IF;

    IF v_order_status = 'pendiente' THEN
      UPDATE public.orders
      SET status = 'pagado',
          cancel_until_at = NOW() + INTERVAL '5 minutes'
      WHERE id = v_link.order_id
        AND business_id = v_link.business_id
        AND payment_method::TEXT = 'wompi'
        AND status::TEXT = 'pendiente'
        AND ROUND(total_amount * 100)::BIGINT = v_link.amount_in_cents;
      IF NOT FOUND THEN RAISE EXCEPTION 'Wompi payment does not match a pending order'; END IF;
      UPDATE public.wompi_transactions
      SET applied_at = NOW(), updated_at = NOW()
      WHERE transaction_id = p_transaction_id;
      RETURN TRUE;
    END IF;

    INSERT INTO public.order_refunds (
      order_id, transaction_id, amount_in_cents, reason
    )
    VALUES (
      v_link.order_id, p_transaction_id, p_amount_in_cents,
      CASE WHEN v_order_status = 'cancelado' THEN 'payment_after_cancellation' ELSE 'duplicate_payment' END
    )
    ON CONFLICT (transaction_id) DO NOTHING;
    UPDATE public.wompi_transactions
    SET applied_at = NOW(), updated_at = NOW()
    WHERE transaction_id = p_transaction_id;
    RETURN FALSE;
  ELSIF v_link.purpose = 'wallet' THEN
    -- Lock the business before its wallet to prevent cycles with transfer acceptance.
    PERFORM 1 FROM public.businesses WHERE id = v_link.business_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Wompi business not found'; END IF;
    UPDATE public.wallets
    SET balance = balance + (v_link.amount_in_cents::NUMERIC / 100),
        updated_at = NOW()
    WHERE id = (
      SELECT id FROM public.wallets
      WHERE business_id = v_link.business_id
      ORDER BY id LIMIT 1 FOR UPDATE
    );
    IF NOT FOUND THEN
      INSERT INTO public.wallets (business_id, balance)
      VALUES (v_link.business_id, v_link.amount_in_cents::NUMERIC / 100);
    END IF;
    UPDATE public.businesses
    SET status = 'activo'
    WHERE id = v_link.business_id AND status = 'fuera_de_servicio';
  ELSE
    PERFORM 1 FROM public.businesses WHERE id = v_link.business_id FOR UPDATE;
    SELECT id, end_date INTO v_subscription_id, v_subscription_end
    FROM public.subscriptions
    WHERE business_id = v_link.business_id
    ORDER BY end_date DESC, id LIMIT 1 FOR UPDATE;
    IF FOUND THEN
      UPDATE public.subscriptions
      SET is_active = TRUE,
          start_date = CASE WHEN end_date >= CURRENT_DATE THEN start_date ELSE CURRENT_DATE END,
          end_date = GREATEST(end_date, CURRENT_DATE) + 30
      WHERE id = v_subscription_id;
    ELSE
      INSERT INTO public.subscriptions (business_id, start_date, end_date, is_active)
      VALUES (v_link.business_id, CURRENT_DATE, CURRENT_DATE + 30, TRUE);
    END IF;
    UPDATE public.businesses
    SET status = 'activo'
    WHERE id = v_link.business_id AND status = 'fuera_de_servicio';
  END IF;

  UPDATE public.wompi_transactions
  SET applied_at = NOW(), updated_at = NOW()
  WHERE transaction_id = p_transaction_id;
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.apply_wompi_payment(TEXT, TEXT, BIGINT, TEXT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.apply_wompi_payment(TEXT, TEXT, BIGINT, TEXT, TEXT)
  TO service_role;

NOTIFY pgrst, 'reload schema';
COMMIT;

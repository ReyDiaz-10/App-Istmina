CREATE OR REPLACE FUNCTION public.admin_record_withdrawal_result(
  p_withdrawal_id UUID,
  p_status TEXT,
  p_provider TEXT DEFAULT NULL,
  p_provider_reference TEXT DEFAULT NULL,
  p_failure_reason TEXT DEFAULT NULL
)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_row public.driver_withdrawals%ROWTYPE;
BEGIN
  IF NOT public.is_superadmin() THEN
    RAISE EXCEPTION 'SuperAdmin access required' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('processing','paid','failed','cancelled') THEN
    RAISE EXCEPTION 'Invalid withdrawal status';
  END IF;
  UPDATE public.driver_withdrawals SET
    status = p_status,
    provider = COALESCE(NULLIF(BTRIM(p_provider), ''), provider),
    provider_reference = COALESCE(NULLIF(BTRIM(p_provider_reference), ''), provider_reference),
    failure_reason = CASE WHEN p_status = 'failed' THEN NULLIF(BTRIM(p_failure_reason), '') ELSE NULL END,
    paid_at = CASE WHEN p_status = 'paid' THEN NOW() ELSE paid_at END
  WHERE id = p_withdrawal_id AND status IN ('scheduled', 'processing')

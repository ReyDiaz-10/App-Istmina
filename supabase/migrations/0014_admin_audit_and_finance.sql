CREATE OR REPLACE FUNCTION public.write_system_audit_log(
  p_actor_id UUID,
  p_action TEXT,
  p_entity_type TEXT DEFAULT NULL,
  p_entity_id TEXT DEFAULT NULL,
  p_metadata JSONB DEFAULT '{}'::JSONB
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_name TEXT;
  v_role TEXT;
BEGIN
  SELECT p.full_name, p.role::TEXT INTO v_name, v_role
  FROM public.profiles p WHERE p.id = p_actor_id;
  IF p_actor_id IS NULL OR v_role IS NULL THEN RETURN; END IF;

  INSERT INTO public.system_audit_logs (
    actor_id, actor_name, actor_role, action, entity_type, entity_id, metadata
  ) VALUES (
    p_actor_id,
    COALESCE(NULLIF(BTRIM(v_name), ''), 'Usuario sin nombre'),
    v_role,
    LEFT(BTRIM(p_action), 160),
    NULLIF(LEFT(BTRIM(COALESCE(p_entity_type, '')), 80), ''),
    NULLIF(LEFT(COALESCE(p_entity_id, ''), 120), ''),
    COALESCE(p_metadata, '{}'::JSONB)
  );
END;
$$;
REVOKE ALL ON FUNCTION public.write_system_audit_log(UUID, TEXT, TEXT, TEXT, JSONB) FROM PUBLIC, anon, authenticated;


CREATE OR REPLACE FUNCTION public.credit_driver_delivery_and_schedule_withdrawal()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_balance NUMERIC(12, 2);
  v_now_local TIMESTAMP;
  v_run_local TIMESTAMP;
BEGIN
  IF NEW.status::TEXT = 'entregado'
     AND OLD.status::TEXT IS DISTINCT FROM 'entregado'
     AND NEW.driver_id IS NOT NULL
     AND COALESCE(NEW.delivery_fee_cop, 0) > 0 THEN
    INSERT INTO public.driver_wallet_entries (driver_id, order_id, entry_type, amount_cop, description)
    VALUES (NEW.driver_id, NEW.id, 'earning', COALESCE(NEW.delivery_fee_cop, 0), 'Domicilio de pedido entregado')
    ON CONFLICT (order_id) DO NOTHING;

    SELECT COALESCE((SELECT SUM(e.amount_cop) FROM public.driver_wallet_entries e WHERE e.driver_id = NEW.driver_id), 0)
      - COALESCE((SELECT SUM(w.amount_cop) FROM public.driver_withdrawals w WHERE w.driver_id = NEW.driver_id AND w.status IN ('scheduled', 'processing', 'paid')), 0)
    INTO v_balance;

    IF v_balance >= 20000 AND NOT EXISTS (
      SELECT 1 FROM public.driver_withdrawals w WHERE w.driver_id = NEW.driver_id AND w.status IN ('scheduled', 'processing')
    ) THEN
      v_now_local := NOW() AT TIME ZONE 'America/Bogota';
      v_run_local := v_now_local::DATE + TIME '03:00';
      IF v_run_local <= v_now_local THEN v_run_local := v_run_local + INTERVAL '1 day'; END IF;
      INSERT INTO public.driver_withdrawals (driver_id, amount_cop, status, scheduled_for)
      VALUES (NEW.driver_id, v_balance, 'scheduled', v_run_local AT TIME ZONE 'America/Bogota');
      PERFORM public.write_system_audit_log(
        (SELECT d.profile_id FROM public.drivers d WHERE d.id = NEW.driver_id),
        'programó un retiro', 'withdrawal', NEW.driver_id::TEXT,
        jsonb_build_object('amount_cop', v_balance, 'scheduled_for', v_run_local));
    END IF;
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS credit_driver_delivery_and_schedule_withdrawal ON public.orders;
CREATE TRIGGER credit_driver_delivery_and_schedule_withdrawal
  AFTER UPDATE OF status ON public.orders
  FOR EACH ROW EXECUTE FUNCTION public.credit_driver_delivery_and_schedule_withdrawal();

INSERT INTO public.driver_wallet_entries (driver_id, order_id, entry_type, amount_cop, description)
SELECT o.driver_id, o.id, 'earning', o.delivery_fee_cop, 'Domicilio de pedido entregado (histórico)'
FROM public.orders o
WHERE o.status::TEXT = 'entregado' AND o.driver_id IS NOT NULL AND o.delivery_fee_cop > 0
ON CONFLICT (order_id) DO NOTHING;

WITH balances AS (
  SELECT e.driver_id, SUM(e.amount_cop) AS balance
  FROM public.driver_wallet_entries e
  GROUP BY e.driver_id
  HAVING SUM(e.amount_cop) >= 20000
), local_time AS (
  SELECT CURRENT_TIMESTAMP AT TIME ZONE 'America/Bogota' AS now_local
)
INSERT INTO public.driver_withdrawals (driver_id, amount_cop, status, scheduled_for)
SELECT b.driver_id, b.balance, 'scheduled',
  ((lt.now_local::DATE + TIME '03:00'
    + CASE WHEN lt.now_local::TIME >= TIME '03:00' THEN INTERVAL '1 day' ELSE INTERVAL '0' END)
   AT TIME ZONE 'America/Bogota')
FROM balances b CROSS JOIN local_time lt
WHERE NOT EXISTS (
  SELECT 1 FROM public.driver_withdrawals w
  WHERE w.driver_id = b.driver_id AND w.status IN ('scheduled', 'processing')
);

CREATE OR REPLACE FUNCTION public.admin_financial_summary()
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE result JSONB;
BEGIN
  IF NOT public.is_superadmin() THEN
    RAISE EXCEPTION 'SuperAdmin access required' USING ERRCODE = '42501';
  END IF;
  SELECT jsonb_build_object(
    'businesses', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'business_id', b.id, 'store_name', b.store_name, 'owner_name', p.full_name,
        'wallet_balance', COALESCE(w.balance, 0), 'pro_active', COALESCE(s.is_active, false),
        'sales_gross', COALESCE(o.sales_gross, 0), 'commission_10_percent', COALESCE(o.commission, 0),
        'sales_net', COALESCE(o.sales_gross, 0) - CASE WHEN COALESCE(s.is_active, false) THEN 0 ELSE COALESCE(o.commission, 0) END
      ) ORDER BY b.store_name)
      FROM public.businesses b
      LEFT JOIN public.profiles p ON p.id = b.profile_id
      LEFT JOIN LATERAL (SELECT SUM(balance) AS balance FROM public.wallets WHERE business_id = b.id) w ON TRUE
      LEFT JOIN LATERAL (SELECT BOOL_OR(is_active AND start_date <= CURRENT_DATE AND end_date >= CURRENT_DATE) AS is_active FROM public.subscriptions WHERE business_id = b.id) s ON TRUE
      LEFT JOIN LATERAL (
        SELECT SUM(COALESCE(product_subtotal_cop, total_amount - COALESCE(delivery_fee_cop, 0))) AS sales_gross,
          SUM(ROUND(COALESCE(product_subtotal_cop, total_amount - COALESCE(delivery_fee_cop, 0)) * 0.10, 2)) AS commission
        FROM public.orders WHERE business_id = b.id AND status::TEXT IN ('pagado','preparando','listo_para_repartidor','en_camino','entregado')
      ) o ON TRUE
    ), '[]'::JSONB),
    'drivers', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'driver_id', d.id, 'profile_id', d.profile_id, 'full_name', p.full_name,
        'earned', COALESCE(e.earned, 0), 'withdrawn', COALESCE(w.withdrawn, 0),
        'reserved', COALESCE(w.reserved, 0),
        'available_balance', COALESCE(e.earned, 0) - COALESCE(w.withdrawn, 0) - COALESCE(w.reserved, 0)
      ) ORDER BY p.full_name)
      FROM public.drivers d LEFT JOIN public.profiles p ON p.id = d.profile_id
      LEFT JOIN LATERAL (SELECT SUM(amount_cop) AS earned FROM public.driver_wallet_entries WHERE driver_id = d.id) e ON TRUE
      LEFT JOIN LATERAL (
        SELECT SUM(amount_cop) FILTER (WHERE status = 'paid') AS withdrawn,
          SUM(amount_cop) FILTER (WHERE status IN ('scheduled','processing')) AS reserved
        FROM public.driver_withdrawals WHERE driver_id = d.id
      ) w ON TRUE
    ), '[]'::JSONB),
    'withdrawals', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', w.id, 'driver_id', w.driver_id, 'full_name', p.full_name,
        'amount_cop', w.amount_cop, 'status', w.status, 'scheduled_for', w.scheduled_for,
        'paid_at', w.paid_at, 'provider_reference', w.provider_reference, 'failure_reason', w.failure_reason
      ) ORDER BY w.scheduled_for DESC)
      FROM public.driver_withdrawals w
      JOIN public.drivers d ON d.id = w.driver_id
      JOIN public.profiles p ON p.id = d.profile_id
    ), '[]'::JSONB),
    'business_wallet_total', (SELECT COALESCE(SUM(balance), 0) FROM public.wallets)
  ) INTO result;
  RETURN result;
END; $$;
REVOKE ALL ON FUNCTION public.admin_financial_summary() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_financial_summary() TO authenticated, service_role;


        auth.uid(),
      CASE WHEN p_status = 'paid' THEN 'registró un retiro desembolsado' ELSE 'actualizó un retiro: ' || p_status END,
      'withdrawal', v_row.id::TEXT,
        jsonb_build_object('amount_cop', v_row.amount_cop, 'status', p_status,
          'driver_id', v_row.driver_id, 'provider_reference', v_row.provider_reference));

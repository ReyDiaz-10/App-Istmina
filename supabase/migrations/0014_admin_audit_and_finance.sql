      SELECT d.profile_id INTO v_actor FROM public.drivers d WHERE d.id = NEW.driver_id;
    ELSIF v_actor IS NULL AND NEW.status::TEXT = 'preparando' THEN
      SELECT b.profile_id INTO v_actor FROM public.businesses b WHERE b.id = NEW.business_id;
    END IF;
    IF v_actor IS NOT NULL THEN
      PERFORM public.write_system_audit_log(v_actor, 'actualizó el estado del pedido', 'order', NEW.id::TEXT,
        jsonb_build_object('previous_status', OLD.status::TEXT, 'status', NEW.status::TEXT));
    END IF;
  END IF;
  RETURN NEW;
END; $$;
